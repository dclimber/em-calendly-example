/// Writes `lib/landing/event_model.g.dart` from the event model, for the landing page.
///
/// Usage: `dart run tool/generate_event_model.dart <diagram.html> <model.em.hcl> <out.dart> [--check]`
///
/// `<diagram.html>` is the output of `emhcl diagram <model.em.hcl>`. emhcl embeds its validated model as JSON in
/// `const FULL_MODEL = {...};`, so this tool needs no HCL parser of its own. The JSON has no chapter descriptions,
/// so they come from the `chapter` blocks of `<model.em.hcl>`. With `--check`, the tool writes nothing and exits
/// with 1 when `<out.dart>` is out of date.
library;

import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final paths = args.where((a) => a != '--check').toList();
  if (paths.length != 3) {
    stderr.writeln('usage: generate_event_model.dart <diagram.html> <model.em.hcl> <out.dart> [--check]');
    exit(64);
  }
  final [diagramPath, modelPath, outPath] = paths;
  final model = _fullModel(File(diagramPath).readAsStringSync());
  final descriptions = _chapterDescriptions(File(modelPath).readAsStringSync());
  final source = await _format(_render(model, descriptions, modelPath));

  final out = File(outPath);
  if (!check) {
    out.writeAsStringSync(source);
    stdout.writeln('wrote $outPath');
  } else if (!out.existsSync() || out.readAsStringSync() != source) {
    stderr.writeln('$outPath is out of date with $modelPath. Run `make event-model`.');
    exit(1);
  }
}

Map<String, Object?> _fullModel(String html) {
  const marker = 'const FULL_MODEL = ';
  final line = const LineSplitter()
      .convert(html)
      .firstWhere(
        (l) => l.startsWith(marker),
        orElse: () => throw const FormatException('The diagram has no FULL_MODEL. Did the emhcl version change?'),
      );
  final json = line.substring(marker.length).trimRight();
  return jsonDecode(json.endsWith(';') ? json.substring(0, json.length - 1) : json) as Map<String, Object?>;
}

Map<String, String> _chapterDescriptions(String hcl) => {
  for (final m in RegExp(
    r'^chapter "(\w+)" \{\n(?:  .*\n)*?  description\s*= "((?:[^"\\]|\\.)*)"',
    multiLine: true,
  ).allMatches(hcl))
    m[1]!: jsonDecode('"${m[2]}"') as String,
};

String _render(Map<String, Object?> model, Map<String, String> descriptions, String modelPath) {
  final slices = {for (final s in _list(model['slices'])) s['id'] as String: s};
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_event_model.dart from $modelPath. Do not edit; run `make event-model`.')
    ..writeln()
    ..writeln("import 'event_model.dart';")
    ..writeln()
    ..writeln('const eventModel = EventModel(')
    ..writeln('chapters: [');
  // The JSON lists the chapters by name; the board order is the order of the `chapter` blocks.
  final order = descriptions.keys.toList();
  final chapters = _list(model['chapters'])
    ..sort((a, b) => order.indexOf(a['id']! as String) - order.indexOf(b['id']! as String));
  for (final chapter in chapters) {
    final name = chapter['id'] as String;
    out
      ..writeln('ModelChapter(${_str(name)},')
      ..writeln('title: ${_str(chapter['title'] as String)},')
      ..writeln('description: ${_str(descriptions[name] ?? '')},')
      ..writeln('slices: [');
    for (final id in (chapter['slices'] as List).cast<String>()) {
      _slice(out, slices[id]!);
    }
    out.writeln('],),');
  }
  out.writeln('],');

  out.writeln('contexts: [');
  for (final node in _list((model['contextMap'] as Map)['nodes'])) {
    final external = node['external'] == true ? ', external: true' : '';
    out.writeln('ModelContext(${_str(node['id'] as String)}, events: ${node['events']}$external),');
  }
  out
    ..writeln('],')
    ..writeln('actors: [${(model['actors'] as Map).keys.map((a) => _str(a as String)).join(', ')}],')
    ..writeln(');');
  return out.toString();
}

void _slice(StringBuffer out, Map<String, Object?> slice) {
  final elements = _list(slice['elements'])..sort((a, b) => (a['stage'] as int).compareTo(b['stage'] as int));
  out
    ..writeln('ModelSlice(${_str(slice['id'] as String)}, SliceKind.${_kind(slice['type'] as String)},')
    ..writeln('description: ${_str(slice['description'] as String? ?? '')},')
    ..writeln('stages: ${slice['stageCount']},')
    ..writeln('elements: [');
  for (final e in elements) {
    final context = e['ctx'] == null ? '' : ', context: ${_str(e['ctx'] as String)}';
    final external = e['external'] == true ? ', external: true' : '';
    out.writeln(
      'ModelElement(ElementKind.${e['kind']}, ${_str(e['title'] as String)}, ${e['stage']}$context$external),',
    );
  }
  out.writeln('],');
  out.writeln('scenarios: [');
  for (final s in _list(slice['scenarios'])) {
    final when = s['when'] == null ? '' : 'when: ${_step(s['when'] as Map<String, Object?>)},';
    out.writeln(
      'ModelScenario(${_str(s['title'] as String)}, '
      'given: [${_list(s['given']).map(_step).join(', ')}], $when '
      'then: [${_list(s['then']).map(_step).join(', ')}],),',
    );
  }
  out.writeln('],),');
}

String _step(Map<String, Object?> step) {
  final kind = step['refKind'] as String;
  final name = kind == 'error' ? step['error'] as String : step['ref'] as String;
  return 'ScenarioStep(ElementKind.$kind, ${_str(name)})';
}

String _kind(String type) => switch (type) {
  'state_change' => 'stateChange',
  'state_view' => 'stateView',
  'automation' => 'automation',
  'translation' => 'translation',
  _ => throw FormatException('Unknown workflow type $type'),
};

List<Map<String, Object?>> _list(Object? value) => [
  for (final v in (value as List?) ?? const []) v as Map<String, Object?>,
];

/// A Dart string literal of [value].
String _str(String value) => "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

/// [source] in the format of `dart format` with the project's settings (page width 120).
Future<String> _format(String source) async {
  final dir = Directory('.dart_tool/event_model')..createSync(recursive: true);
  final file = File('${dir.path}/event_model.g.dart')..writeAsStringSync(source);
  final result = await Process.run(Platform.resolvedExecutable, ['format', '--page-width=120', file.path]);
  if (result.exitCode != 0) throw StateError('dart format failed: ${result.stderr}');
  return file.readAsStringSync();
}
